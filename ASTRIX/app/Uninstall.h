#pragma once
// Сброс настроек и полное удаление программы (Windows: реестр автозапуска, папка программы).
// На Linux понадобится своя реализация этих двух функций — остальной код их только вызывает.

#include <string>

namespace Uninstall {
    std::wstring Folder();   // что будет удалено (папка программы)
    bool SafeToDeleteFolder(); // папка — своя (не диск целиком и не «Рабочий стол»): удаляем её целиком, иначе — только свои файлы

    void ResetSettings();    // все настройки по умолчанию (телеграм, Discord и контакты остаются) — и перезапуск
    void RemoveEverything(); // убрать автозапуск, удалить папку со всеми данными и закрыться
}

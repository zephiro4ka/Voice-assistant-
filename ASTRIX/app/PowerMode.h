#pragma once
// Питание компьютера. Главное — «Аня на связи»: вместо настоящего выключения гасим экран, блокируем,
// выключаем звук и не даём уснуть — компьютер выглядит выключенным, а телеграм-бот работает и может «включить» его обратно.
// (Полностью выключенный компьютер не включить ни одной программой: для этого нужен Wake-on-LAN и второе устройство в сети.)

namespace PowerMode {
    void Standby();      // «выключить, но остаться на связи»
    void Wake();         // включить экран и звук обратно
    bool IsStandby();

    void Shutdown(int delaySeconds = 15);  // выключить по-настоящему (бот тоже отключится)
    void Restart(int delaySeconds = 15);
    void CancelShutdown();
    void Lock();

    // Блокировка Windows (Win+L, кнопка в телеграме, автоблокировка) — приходит из оконных событий сеанса
    void SetLocked(bool locked);
    bool IsLocked();
}

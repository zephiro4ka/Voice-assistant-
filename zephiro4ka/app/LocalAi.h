#pragma once
// Нейросеть Ани — прямо из файла модели .gguf, без Ollama и без окна LM Studio.
// Аня сама скрыто запускает llama-server (официальный движок llama.cpp, на нём же работает LM Studio)
// на видеокарте, а при закрытии Ани Windows закрывает его вместе с ней.

#include <string>
#include <vector>

namespace Ai {
    void Start();      // в фоне: найти модель, запустить движок, дождаться готовности
    void Restart();    // перезапустить с другой моделью (после смены в настройках)

    // Ответ нейросети. Если просьба была «сделай что-то на компьютере», нейросеть не отвечает словами,
    // а переводит её в точные команды Ани («зайди в чат с прыщавый») — их выполняют навыки.
    struct Answer {
        bool ok = false;                      // нейросеть ответила
        std::vector<std::string> commands;    // переведённые команды (пусто — это был обычный ответ)
    };

    // Спросить нейросеть. Обычный ответ печатается в чат по мере генерации и озвучивается по предложениям.
    Answer Ask(const std::string& prompt);

    // Тихий ответ целиком — без озвучки и без чата (для телеграма). image — JPEG в base64: модель «смотрит» на снимок.
    // Пустая строка — нейросеть не ответила.
    // deep — задача: модель сначала думает «про себя» (до нескольких минут) и проверяет ответ, потом пишет решение
    std::string Quiet(const std::string& prompt, const std::string& imageBase64 = "", bool deep = false);
    // Ответ строго в JSON — со своей инструкцией, без характера и команд Ани (для сборки сценариев). Пусто — не ответила.
    std::string AskJson(const std::string& instruction, const std::string& request);
    bool LooksLikeTask(const std::string& prompt); // «реши», «найди x», уравнение, задача…
    bool CanSee(); // у модели есть «глаза» (файл mmproj рядом с моделью) — можно присылать картинки

    std::vector<std::string> Models();   // найденные модели .gguf (полные пути)
    std::string ActiveModel();           // имя файла текущей модели
}
